package moe.nea.frobmatrix.fxutils.processor;

import moe.nea.frobmatrix.fxutils.annotations.FXPropertyAccessors;

import java.io.IOException;
import java.io.PrintWriter;
import java.util.*;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedSourceVersion;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.TypeParameterElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;

@SupportedSourceVersion(SourceVersion.RELEASE_25)
public class FXPropertyProcessor extends AbstractProcessor {

	private static final Map<String, String> KNOWN_PROPERTY_TYPES = Map.ofEntries(
		Map.entry("StringProperty", "String"),
		Map.entry("IntegerProperty", "int"),
		Map.entry("DoubleProperty", "double"),
		Map.entry("FloatProperty", "float"),
		Map.entry("LongProperty", "long"),
		Map.entry("BooleanProperty", "boolean"),
		// Add read only because why not
		Map.entry("ReadOnlyStringProperty", "String"),
		Map.entry("ReadOnlyIntegerProperty", "int"),
		Map.entry("ReadOnlyDoubleProperty", "double"),
		Map.entry("ReadOnlyFloatProperty", "float"),
		Map.entry("ReadOnlyLongProperty", "long"),
		Map.entry("ReadOnlyBooleanProperty", "boolean"));

	record PropData(String propertyName, TypeMirror propType, String valueType, boolean readOnly) {
		String propertyNameCapitalized() {
			return propertyName.substring(0, 1).toUpperCase(Locale.ROOT) + propertyName.substring(1);
		}
	}

	static class TypeData {
		TypeElement type;
		List<PropData> propData = new ArrayList<>();

		TypeData(TypeElement element) {
			this.type = element;
		}
	}

	@Override
	public boolean process(Set<? extends TypeElement> set, RoundEnvironment roundEnvironment) {
		if (roundEnvironment.processingOver()) return false;
		Map<String, TypeData> roundData = new HashMap<>();

		for (var element : roundEnvironment.getElementsAnnotatedWith(FXPropertyAccessors.class)) {
			if (element.getKind() != ElementKind.METHOD) {
				processingEnv
					.getMessager()
					.printError(
						FXPropertyAccessors.class.getSimpleName() + " can only be applied to methods", element);
				continue;
			}
			var executable = ((ExecutableElement) element);
			var containingClass = (TypeElement) element.getEnclosingElement();
			var methodName = element.getSimpleName().toString();
			if (!methodName.endsWith("Property")) {
				processingEnv
					.getMessager()
					.printError(
						FXPropertyAccessors.class.getSimpleName() + " can only be applied to xProperty methods",
						element);
				continue;
			}
			var propertyName = methodName.substring(0, methodName.length() - "Property".length());
			assert !propertyName.isEmpty();
			if (!executable.getParameters().isEmpty()) {
				processingEnv
					.getMessager()
					.printError(
						FXPropertyAccessors.class.getSimpleName()
							+ " can only be applied to parameter less methods",
						element);
				continue;
			}
			var returnType = executable.getReturnType();
			var valueType = resolveValueType(returnType);

			var typeData = roundData.computeIfAbsent(
				containingClass.getQualifiedName().toString(), ignored -> new TypeData(containingClass));
			typeData.propData.add(new PropData(
				propertyName, returnType, valueType, returnType.toString().contains("ReadOnly")));
		}

		for (var typeData : roundData.values()) {
			// TODO: warn for missing interface
			try {
				writeInterfaceType(typeData);
			} catch (IOException e) {
				throw new RuntimeException(e);
			}
		}
		return !roundData.isEmpty();
	}

	private void writeInterfaceType(TypeData typeData) throws IOException {
		var propIFaceName = typeData.type.getSimpleName() + "Props";
		var typeParams = typeData.type.getTypeParameters();

		var packageName =
			processingEnv.getElementUtils().getPackageOf(typeData.type).getQualifiedName();
		var file = processingEnv
			.getFiler()
			.createSourceFile(
				processingEnv
					.getElementUtils()
					.getPackageOf(typeData.type)
					.getQualifiedName() + "." + propIFaceName,
				typeData.type);
		try (var writer = new PrintWriter(file.openWriter())) {
			writer.println("// @generated by " + getClass().getName());
			writer.println("package " + packageName + ";");
			writer.println();
			writer.printf("/** Generated property accessors for {@link %s}*/%n", typeData.type.getSimpleName());
			writer.print("public abstract class " + propIFaceName);
			if (!typeParams.isEmpty()) {
				writer.print("<");
				for (var typeParam : typeParams) {
					writer.print(typeParam.getSimpleName());
				}
				writer.print(">");
			}
			writer.println(" {");
			for (var prop : typeData.propData) {
				writer.printf("\t/** @see %s#%sProperty */%n", typeData.type.getSimpleName(), prop.propertyName());
				writer.printf("\tpublic abstract %s %sProperty();%n", prop.propType, prop.propertyName());
				writer.printf("\t/** Getter for {@link #%sProperty} */%n", prop.propertyName());
				writer.printf(
					"\tpublic %s get%s() { return %sProperty().get(); }%n",
					prop.valueType(), prop.propertyNameCapitalized(), prop.propertyName());
				if (!prop.readOnly()) {
					writer.printf("\t/** Setter for {@link #%sProperty} */%n", prop.propertyName());
					writer.printf(
						"\tpublic void set%s(%s value) { %sProperty().set(value); }%n",
						prop.propertyNameCapitalized(), prop.valueType(), prop.propertyName());
				}
			}
			writer.println("}");
		}
	}

	private String resolveValueType(TypeMirror propertyType) {
		var declaredType = (DeclaredType) propertyType;
		var simpleName = (declaredType.asElement()).getSimpleName().toString();
		var overrideType = KNOWN_PROPERTY_TYPES.get(simpleName);
		if (overrideType != null) return overrideType;
		return resolveObjectPropertyType(declaredType);
	}

	private String resolveObjectPropertyType(DeclaredType declaredType) {
		var simpleName = declaredType.asElement().getSimpleName().toString();
		if ("ObjectProperty".equals(simpleName) || "ReadOnlyObjectProperty".equals(simpleName)) {
			var typeArgs = declaredType.getTypeArguments();
			assert typeArgs.size() == 1;
			return typeArgs.getFirst().toString();
		}
		if ("ListProperty".equals(simpleName) || "ReadOnlyListProperty".equals(simpleName)) {
			var typeArgs = declaredType.getTypeArguments();
			assert typeArgs.size() == 1;
			return "javafx.collections.ObservableList<" + typeArgs.getFirst().toString() + ">";
		}
		throw new RuntimeException("Could not resolve object type for property type " + declaredType);
	}

	@Override
	public Set<String> getSupportedAnnotationTypes() {
		return Set.of(FXPropertyAccessors.class.getName());
	}
}
